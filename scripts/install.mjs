// Installs the agent into a host that has no Claude-style plugin loader, by generating that host's files
// from the canonical ones (skills/, agents/, hooks/). Claude Code needs no install: use --plugin-dir.
//   node install.mjs --provider antigravity|kiro [--scope workspace|global] [--dest <workspace dir>] [--probe on]
// antigravity, workspace (default): <dest or cwd>/.agents/{skills,agents,hooks.json}; global: ~/.gemini/config/{...}
// kiro, workspace: <dest or cwd>/.kiro/{steering,agents,hooks}; global: ~/.kiro/{...} (CLI and IDE share them)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { globalDir, workspaceDir } from "../providers/antigravity.mjs";
import { globalDir as kiroGlobalDir, workspaceDir as kiroWorkspaceDir } from "../providers/kiro.mjs";
import { ANTIGRAVITY_AGENT_TOOLS, KIRO_AGENT_TOOLS, KIRO_READ_ONLY_TOOLS } from "../providers/tools.mjs";

// fileURLToPath decodes spaces and drive letters; the URL pathname does not
const PLUGIN_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Written into every generated file. A file without it was not made by this installer
const MARKER = "<!-- generated by the dev-agent installer: edit the source files in the dev-agent folder, then run the installer again -->";
// JSON files cannot hold the comment above, so ours carry this tag in their description instead
const JSON_TAG = "[generated by the dev-agent installer]";
const HOOK_TOOLS = "run_command|view_file|write_to_file|replace_file_content|multi_replace_file_content|grep_search|list_dir|find_by_name";

const read = (...p) => fs.readFileSync(path.join(PLUGIN_DIR, ...p), "utf8").replace(/\r\n/g, "\n");
const posix = (p) => p.replace(/\\/g, "/");

function splitFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error("Missing frontmatter");
  const fields = Object.fromEntries(m[1].split("\n").map((l) => [l.slice(0, l.indexOf(":")), l.slice(l.indexOf(":") + 1).trim()]));
  return { fields, body: m[2] };
}

// A differing file that this installer did not write is saved next to it as .bak before it is replaced
function backUp(file) {
  if (!fs.existsSync(file)) return null;
  const old = fs.readFileSync(file, "utf8");
  if (old.includes(MARKER) || old.includes(JSON_TAG)) return null;
  let bak = `${file}.bak`;
  for (let i = 2; fs.existsSync(bak); i++) bak = `${file}.bak${i}`;
  fs.copyFileSync(file, bak);
  return bak;
}

function write(file, text, written) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const bak = fs.existsSync(file) && fs.readFileSync(file, "utf8") === text ? null : backUp(file);
  fs.writeFileSync(file, text);
  written.push(bak ? `${file} (previous version saved as ${bak})` : file);
}

// Antigravity has no skill-directory variable, so the skill gets the plugin folder written in
function skillFor(pluginDir) {
  const { fields, body } = splitFrontmatter(read("skills", "solve-ticket", "SKILL.md"));
  const resolved = body.replace(/<!--plugin-->[\s\S]*?<!--\/plugin-->/, `\`${posix(pluginDir)}\``);
  return `---\nname: ${fields.name}\ndescription: ${fields.description}\n---\n${MARKER}\n${resolved}`;
}

// Claude tool list -> Antigravity tool names; a misspelt name can hang a subagent, so unknown tools throw
function agentFor(file) {
  const { fields, body } = splitFrontmatter(read("agents", file));
  const tools = [...new Set(fields.tools.split(",").flatMap((t) => {
    const mapped = ANTIGRAVITY_AGENT_TOOLS[t.trim()];
    if (!mapped) throw new Error(`No Antigravity tool for ${t.trim()} in agents/${file}`);
    return mapped;
  }))];
  return [
    "---",
    `name: ${fields.name}`,
    `description: ${fields.description}`,
    "tools:",
    ...tools.map((t) => `  - ${t}`),
    "subagent: true",
    "mainAgent: false",
    "model: inherit",
    "---",
    MARKER,
    body,
  ].join("\n");
}

function mergeHooks(file, pluginDir, written, probe = false) {
  let hooks = {};
  try {
    hooks = JSON.parse(fs.readFileSync(file, "utf8").replace(/^﻿/, ""));
  } catch {
    // No hooks file yet, or an unreadable one that is replaced below only when empty
    if (fs.existsSync(file)) throw new Error(`${file} is not valid JSON; fix it or remove it, then run again`);
  }
  hooks["dev-agent"] = {
    PreToolUse: [
      {
        matcher: HOOK_TOOLS,
        hooks: [{ type: "command", command: `node "${posix(pluginDir)}/hooks/guard.mjs"`, timeout: 10 }],
      },
    ],
  };
  // Temporary: logs the raw events so the shape of Antigravity's session data can be read (hooks/dump.mjs)
  if (probe) {
    const dump = [{ hooks: [{ type: "command", command: `node "${posix(pluginDir)}/hooks/dump.mjs"`, timeout: 10 }] }];
    hooks["dev-agent-probe"] = { PostToolUse: dump, Stop: dump };
  } else {
    delete hooks["dev-agent-probe"];
  }
  write(file, `${JSON.stringify(hooks, null, 2)}\n`, written);
}

export function installAntigravity({ baseDir, pluginDir = PLUGIN_DIR, probe = false }) {
  const written = [];
  write(path.join(baseDir, "skills", "solve-ticket", "SKILL.md"), skillFor(pluginDir), written);
  for (const name of ["repo-builder", "repo-reviewer"]) {
    write(path.join(baseDir, "agents", name, "agent.md"), agentFor(`${name}.md`), written);
  }
  mergeHooks(path.join(baseDir, "hooks.json"), pluginDir, written, probe);
  return written;
}

// ---- Kiro (CLI and IDE) ----
// Layout from Kiro's docs: steering files in steering/, CLI custom agents in agents/*.json (with their own
// hooks), IDE hooks in hooks/*.kiro.hook. Hook field names have changed between CLI versions and are not
// verified against a live session: run the installer with --probe on, use Kiro once, then check docs/KIRO.md.
const cmd = (pluginDir, script, args = "") => `node "${posix(pluginDir)}/hooks/${script}"${args}`;

function kiroAgentFor(file, pluginDir, probe) {
  const { fields, body } = splitFrontmatter(read("agents", file));
  const tools = [...new Set(fields.tools.split(",").flatMap((t) => {
    const mapped = KIRO_AGENT_TOOLS[t.trim()];
    if (!mapped) throw new Error(`No Kiro tool for ${t.trim()} in agents/${file}`);
    return mapped;
  }))];
  const dump = probe ? [{ command: cmd(pluginDir, "dump.mjs") }] : [];
  const agent = {
    name: fields.name,
    description: `${fields.description} ${JSON_TAG}`,
    prompt: body.trim(),
    tools,
    // Only read-only tools run without asking; widen allowedTools in the file to run builds unattended
    allowedTools: tools.filter((t) => KIRO_READ_ONLY_TOOLS.includes(t)),
    hooks: {
      preToolUse: [{ matcher: "*", command: cmd(pluginDir, "guard.mjs") }, ...dump],
      stop: [{ command: cmd(pluginDir, "kiro-usage.mjs", " --surface cli") }, ...dump],
    },
  };
  return `${JSON.stringify(agent, null, 2)}\n`;
}

function kiroHook(name, description, when, command) {
  const hook = { enabled: true, name, description: `${description} ${JSON_TAG}`, version: "1", when, then: { type: "runCommand", command } };
  return `${JSON.stringify(hook, null, 2)}\n`;
}

export function installKiro({ baseDir, pluginDir = PLUGIN_DIR, probe = false }) {
  const written = [];
  const { fields, body } = splitFrontmatter(read("skills", "solve-ticket", "SKILL.md"));
  const resolved = body.replace(/<!--plugin-->[\s\S]*?<!--\/plugin-->/, `\`${posix(pluginDir)}\``);
  // inclusion: manual keeps it out of ordinary chats; start it with #dev-agent in the IDE
  const steering = `---\ninclusion: manual\n---\n${MARKER}\n# ${fields.name}: ${fields.description}\n\n${resolved}`;
  write(path.join(baseDir, "steering", "dev-agent.md"), steering, written);
  for (const name of ["repo-builder", "repo-reviewer"]) {
    write(path.join(baseDir, "agents", `${name}.json`), kiroAgentFor(`${name}.md`, pluginDir, probe), written);
  }
  const hooks = path.join(baseDir, "hooks");
  const guardWhen = { type: "preToolUse", toolTypes: ["shell", "read", "write"] };
  write(path.join(hooks, "dev-agent-guard.kiro.hook"), kiroHook("dev-agent safety guard", "Blocks pushes, merges and secret-file access", guardWhen, cmd(pluginDir, "guard.mjs")), written);
  write(path.join(hooks, "dev-agent-usage.kiro.hook"), kiroHook("dev-agent usage log", "Records one request per agent run for session usage", { type: "agentStop" }, cmd(pluginDir, "kiro-usage.mjs", " --surface ide")), written);
  const probeFile = path.join(hooks, "dev-agent-probe.kiro.hook");
  if (probe) {
    write(probeFile, kiroHook("dev-agent probe", "Temporary: logs raw hook events (hooks/dump.mjs)", { type: "agentStop" }, cmd(pluginDir, "dump.mjs")), written);
  } else if (fs.existsSync(probeFile) && fs.readFileSync(probeFile, "utf8").includes(JSON_TAG)) {
    fs.rmSync(probeFile);
  }
  return written;
}

function parseArgs(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!argv[i].startsWith("--") || argv[i + 1] === undefined) throw new Error(`Bad argument: ${argv[i]}`);
    opts[argv[i].slice(2)] = argv[i + 1];
  }
  return opts;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const opts = parseArgs(process.argv.slice(2));
    if (!["antigravity", "kiro"].includes(opts.provider)) throw new Error("Usage: install.mjs --provider antigravity|kiro [--scope workspace|global] [--dest <dir>] [--probe on]");
    const kiro = opts.provider === "kiro";
    const [globalBase, workspaceBase] = kiro ? [kiroGlobalDir, kiroWorkspaceDir] : [globalDir, workspaceDir];
    const baseDir = opts.scope === "global" ? globalBase() : workspaceBase(opts.dest ?? process.cwd());
    for (const file of (kiro ? installKiro : installAntigravity)({ baseDir, probe: opts.probe === "on" })) console.log(`wrote ${file}`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
